package org.vvs.valimbavaka.feature.day.controller;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.ResultActions;

import com.jayway.jsonpath.JsonPath;

import org.vvs.valimbavaka.feature.stock.controller.StockApiTestSupport;
import org.vvs.valimbavaka.feature.stock.domain.StockMovementType;

/** TRF-02: the transfers generated by the opening of the day show up at once, validated, and name their day. */
class MorningTransferIT extends StockApiTestSupport {

    private static final String DAYS = "/api/v1/days";
    private static final String TRANSFERS = "/api/v1/transfers";
    private static final DateTimeFormatter DAY_FORMAT = DateTimeFormatter.ofPattern("dd/MM/yyyy");

    /** One day per date: each test starts with today not opened yet (the sales of VTE-01 reference the day). */
    @BeforeEach
    void forgetToday() {
        // LIV-03: a delivered order references its sale
        jdbcTemplate.update(
                "update delivery_orders set status = 'CANCELLED', sale_id = null where sale_id is not null");
        jdbcTemplate.update("delete from sale_lines");
        jdbcTemplate.update("delete from sales");
        jdbcTemplate.update("delete from business_day_transfers");
        jdbcTemplate.update("delete from business_days");
    }

    @Test
    void openDay_twoDestinations_listsEachMorningTransferAtOnceAsValidatedAndIssuedByTheAdmin() throws Exception {
        // Arrange
        var soap = createArticle(uniqueName());
        move(soap, "WAREHOUSE", StockMovementType.RECEIPT, "20");
        var json = openDay(line(soap, "STORE", "12") + "," + line(soap, "DELIVERY", "5"));
        List<String> numbers = JsonPath.read(json, "$.transfers[*].transferNumber");
        var admin = jdbcTemplate.queryForMap(
                "select cast(id as varchar) as id, first_name || ' ' || last_name as name from users where email = ?",
                ADMIN_EMAIL);

        // Act + Assert
        assertThat(numbers).hasSize(2);
        for (var number : numbers) {
            history(number)
                    .andExpect(status().isOk())
                    .andExpect(jsonPath("$.totalCount").value(1))
                    .andExpect(jsonPath("$.items[0].origin").value("MORNING"))
                    .andExpect(jsonPath("$.items[0].status").value("VALIDATED"))
                    .andExpect(jsonPath("$.items[0].fromLocationId")
                            .value(location("WAREHOUSE").toString()))
                    .andExpect(jsonPath("$.items[0].createdBy").value(admin.get("id")))
                    .andExpect(jsonPath("$.items[0].createdByName").value(admin.get("name")));
        }
    }

    @Test
    void openDay_validDispatch_notesTheOpeningDayOnEachMorningTransfer() throws Exception {
        // Arrange
        var soap = createArticle(uniqueName());
        move(soap, "WAREHOUSE", StockMovementType.RECEIPT, "9");

        // Act
        var json = openDay(line(soap, "STORE", "2") + "," + line(soap, "TRADE_SHOW", "3"));

        // Assert
        var date = LocalDate.parse(JsonPath.read(json, "$.businessDate"));
        List<String> transferIds = JsonPath.read(json, "$.transfers[*].transferId");
        assertThat(transferIds).hasSize(2);
        for (var transferId : transferIds) {
            var note = jdbcTemplate.queryForObject(
                    "select note from transfers where id = ?", String.class, UUID.fromString(transferId));
            assertThat(note).isEqualTo("Ouverture de la journée du " + DAY_FORMAT.format(date));
        }
    }

    @Test
    void openDay_validDispatch_tracesEachMorningTransferInTheJournal() throws Exception {
        // Arrange
        var soap = createArticle(uniqueName());
        move(soap, "WAREHOUSE", StockMovementType.RECEIPT, "4");

        // Act
        var json = openDay(line(soap, "STORE", "4"));

        // Assert
        String transferId = JsonPath.read(json, "$.transfers[0].transferId");
        String number = JsonPath.read(json, "$.transfers[0].transferNumber");
        var description = jdbcTemplate.queryForObject(
                "select description from journal_entries where resource_type = 'TRANSFER' and resource_id = ? "
                        + "and action = 'CREATE'",
                String.class,
                UUID.fromString(transferId));
        assertThat(description).startsWith("Transfert du matin " + number + " · ");
    }

    @Test
    void openDay_aboveWarehouseStock_generatesNoMorningTransfer() throws Exception {
        // Arrange: 3 + 3 asked, 5 at the warehouse.
        var soap = createArticle(uniqueName());
        move(soap, "WAREHOUSE", StockMovementType.RECEIPT, "5");
        var before = morningTransferCount();

        // Act
        submit(body(line(soap, "STORE", "3") + "," + line(soap, "DELIVERY", "3")))
                .andExpect(status().isConflict());

        // Assert
        assertThat(morningTransferCount()).isEqualTo(before);
    }

    private String openDay(String lines) throws Exception {
        return submit(body(lines))
                .andExpect(status().isCreated())
                .andReturn()
                .getResponse()
                .getContentAsString();
    }

    private ResultActions submit(String body) throws Exception {
        return mockMvc.perform(post(DAYS)
                .header(HttpHeaders.AUTHORIZATION, bearer(adminToken()))
                .contentType(MediaType.APPLICATION_JSON)
                .content(body));
    }

    private ResultActions history(String number) throws Exception {
        return mockMvc.perform(get(TRANSFERS)
                .param("origin", "MORNING")
                .param("search", number)
                .header(HttpHeaders.AUTHORIZATION, bearer(adminToken())));
    }

    private Integer morningTransferCount() {
        return jdbcTemplate.queryForObject("select count(*) from transfers where origin = 'MORNING'", Integer.class);
    }

    private static String body(String lines) {
        return "{\"lines\":[%s]}".formatted(lines);
    }

    private String line(UUID articleId, String destinationCode, String quantity) {
        return "{\"articleId\":\"%s\",\"destinationId\":\"%s\",\"quantity\":%s}"
                .formatted(articleId, location(destinationCode), quantity);
    }
}
